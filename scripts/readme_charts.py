#!/usr/bin/env python3
"""Build the animated README charts in assets/ from the bake-off numbers.

    python3 scripts/readme_charts.py

The numbers below are copied from docs/bake-off.md (main table). Change them there
first, then here, then rerun. GitHub renders the SVGs through <img>, so the charts
animate with CSS only and every loop starts and ends at the finished chart.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets"

# Catppuccin Mocha, as in ui/palette.json.
C = {
    "crust": "#11111b", "mantle": "#181825", "base": "#1e1e2e",
    "surface0": "#313244", "surface1": "#45475a",
    "overlay1": "#7f849c", "subtext0": "#a6adc8", "text": "#cdd6f4",
    "accent": "#cba6f7",
}

# Cost for 10 app tasks; every model here passed 10/10.
COST = [
    ("Haiku 5.5 low", 1.44),
    ("DeepSeek V4 Flash", 1.50),
    ("Sonnet 5.5 low", 4.78),
    ("Opus 5.5 low", 8.22),
    ("Opus 5.5 high", 16.12),
    ("Opus 5", 20.60),
    ("Fable 5.1", 26.95),
]

# Review bugs found, of 17; two values = two runs.
REVIEW = [
    ("Opus 5.5 high", (9, 10)),
    ("Gemini 4 Argon", (8, 10)),
    ("DeepSeek V4 Flash", (9,)),
    ("GLM-5.3", (5, 8)),
    ("Grok 4.7", (7,)),
    ("Fable 5.1", (6,)),
    ("Sonnet 5.5 high", (6,)),
    ("GPT-6 Astra", (5,)),
    ("Gemini 3.8 Flash", (5,)),
    ("Kimi K3", (4,)),
    ("GPT-6.1 Sol", (3,)),
]

W = 900
LABEL_X = 230
PLOT_X = 246
PLOT_W = 520
CYCLE = 10

STYLE = f"""
    <style>
      text {{ font-family: "Inter", ui-sans-serif, system-ui, -apple-system,
             "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }}
      /* Draws in on load, holds, then redraws. The attributes hold the finished
         chart, so anything that ignores the CSS still shows it complete. */
      @keyframes draw {{ 0% {{ stroke-dashoffset: 1 }} 26%,86% {{ stroke-dashoffset: 0 }}
                         92%,100% {{ stroke-dashoffset: 1 }} }}
      @keyframes pop  {{ 0%,16% {{ opacity: 0 }} 26%,86% {{ opacity: 1 }} 92%,100% {{ opacity: 0 }} }}
      .draw {{ animation: draw {CYCLE}s cubic-bezier(0.16,1,0.3,1) infinite backwards; }}
      .pop  {{ animation: pop {CYCLE}s ease-out infinite backwards; }}
      @media (prefers-reduced-motion: reduce) {{ * {{ animation: none !important; }} }}
    </style>"""


def frame(h, title, subtitle, desc, body):
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {h}" width="{W}" height="{h}"
     role="img" aria-labelledby="t d" font-family="sans-serif">
  <title id="t">{title}</title>
  <desc id="d">{desc}</desc>
  <!-- Generated by scripts/readme_charts.py from docs/bake-off.md. Do not edit by hand. -->
  <defs>
    <clipPath id="frame"><rect width="{W}" height="{h}" rx="16"/></clipPath>{STYLE}
  </defs>
  <g clip-path="url(#frame)">
    <rect width="{W}" height="{h}" fill="{C['base']}"/>
    <text x="32" y="46" font-size="19" font-weight="600" fill="{C['text']}">{title}</text>
    <text x="32" y="70" font-size="13" fill="{C['subtext0']}">{subtitle}</text>
{body}
  </g>
</svg>
"""


def delay(i):
    return f' style="animation-delay:{i * 0.09:.2f}s"'


def cost_chart():
    top, row = 112, 36
    top_val = max(v for _, v in COST)
    rows = []
    for i, (name, v) in enumerate(COST):
        y = top + i * row
        end = PLOT_X + PLOT_W * v / top_val
        rows.append(f"""    <g><title>{name}: ${v:.2f} for 10 tasks</title>
      <text x="{LABEL_X}" y="{y + 5}" font-size="13" text-anchor="end" fill="{C['text']}">{name}</text>
      <line class="draw"{delay(i)} x1="{PLOT_X}" y1="{y}" x2="{end:.1f}" y2="{y}" pathLength="1"
            stroke="{C['accent']}" stroke-width="18" stroke-dasharray="1" stroke-dashoffset="0"/>
      <text class="pop"{delay(i)} x="{end + 10:.1f}" y="{y + 5}" font-size="13" font-weight="600" fill="{C['text']}">${v:.2f}</text>
    </g>""")
    h = top + len(COST) * row + 8
    return frame(
        h, "What 10 real app tasks cost",
        "Every model passed all 10, so cost decides. Bake-off on one production app, Sep–Oct 2026.",
        "Horizontal bars, cheapest first: " + ", ".join(f"{n} ${v:.2f}" for n, v in COST) + ".",
        "\n".join(rows))


def review_chart():
    top, row, n_bugs = 128, 30, 17
    x = lambda b: PLOT_X + PLOT_W * b / n_bugs
    ticks = "\n".join(
        f'    <text x="{x(t):.1f}" y="{top - 26}" font-size="11" text-anchor="middle" fill="{C["overlay1"]}">{t}</text>'
        for t in (0, 5, 10, 15, 17))
    rows = []
    for i, (name, runs) in enumerate(REVIEW):
        y = top + i * row
        lo, hi = min(runs), max(runs)
        label = f"{lo}–{hi}" if lo != hi else f"{lo}"
        dots = "\n".join(
            f'      <circle class="pop"{delay(i)} cx="{x(r):.1f}" cy="{y}" r="6" fill="{C["accent"]}" '
            f'stroke="{C["base"]}" stroke-width="2"/>' for r in sorted(set(runs)))
        rows.append(f"""    <g><title>{name}: {label} of 17 bugs</title>
      <text x="{LABEL_X}" y="{y + 4.5}" font-size="13" text-anchor="end" fill="{C['text']}">{name}</text>
      <line x1="{x(0):.1f}" y1="{y}" x2="{x(n_bugs):.1f}" y2="{y}" stroke="{C['surface0']}" stroke-width="2" stroke-linecap="round"/>
      <line class="draw"{delay(i)} x1="{x(0):.1f}" y1="{y}" x2="{x(lo):.1f}" y2="{y}" pathLength="1"
            stroke="{C['accent']}" stroke-opacity="0.45" stroke-width="2" stroke-dasharray="1" stroke-dashoffset="0"/>
      <line x1="{x(lo):.1f}" y1="{y}" x2="{x(hi):.1f}" y2="{y}" class="pop"{delay(i)}
            stroke="{C['accent']}" stroke-width="8" stroke-linecap="round"/>
{dots}
      <text class="pop"{delay(i)} x="{x(n_bugs) + 18:.1f}" y="{y + 4.5}" font-size="13" font-weight="600" fill="{C['text']}">{label}</text>
    </g>""")
    h = top + len(REVIEW) * row + 12
    return frame(
        h, "Real bugs each reviewer found, of 17",
        "5 review cases from real commits. Two dots are two runs. Every model missed most security-rules bugs.",
        "Dot plot, best first: " + ", ".join(
            f"{n} {'-'.join(str(r) for r in rs)}" for n, rs in REVIEW) + " of 17 bugs.",
        ticks + "\n" + "\n".join(rows))


def main():
    OUT.mkdir(exist_ok=True)
    (OUT / "cost-chart.svg").write_text(cost_chart())
    (OUT / "review-chart.svg").write_text(review_chart())
    print("wrote assets/cost-chart.svg, assets/review-chart.svg")


if __name__ == "__main__":
    main()
